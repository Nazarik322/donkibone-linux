#!/usr/bin/env bash
# Builds the Celestia installer ISO. Run inside Arch Linux (WSL2) as your normal
# user, after scripts/setup-build-env.sh. The ISO lands in ./out/.
#
#   ./build.sh            full build (theme -> packages -> offline repo -> ISO)
#   CELESTIA_RESTORE=1 ./build.sh   start from the packages of the published channel
#   ./build.sh --clean    also rebuild every package from scratch (drops the build
#                         chroot, build stamps and the local package repo)
set -euo pipefail

src_dir="$(cd "$(dirname "$0")" && pwd)"

# mkarchiso needs a Linux filesystem (permissions, symlinks). When started from
# the Windows drive (/mnt/c/...), work on a copy in the Linux home and put the
# ISO back next to the sources.
if [[ "$src_dir" == /mnt/* && -z "${CELESTIA_IN_COPY:-}" ]]; then
    copy="$HOME/celestia-src"
    echo "==> Copying sources to $copy (building on /mnt/c is not supported)"
    mkdir -p "$copy"
    rsync -a --delete --exclude '/out/' --exclude '/work/' "$src_dir/" "$copy/"
    # Files edited on Windows may have CRLF line endings; bash and pacman need LF.
    grep -rlIZ $'\r' "$copy" --exclude-dir=.git | xargs -0 -r sed -i 's/\r$//'
    CELESTIA_IN_COPY=1 CELESTIA_OUT="$src_dir/out" exec "$copy/build.sh" "$@"
fi

source "$src_dir/scripts/common.sh"
out_dir="${CELESTIA_OUT:-$ROOT_DIR/out}"
archiso_work="$WORK_DIR/archiso"
profile_dir="$WORK_DIR/profile"

[[ $EUID -ne 0 ]] || die "run as your normal user, not root (sudo is used where needed)"

# Builds share $WORK_DIR and the local repo: only one at a time.
mkdir -p "$WORK_DIR"
exec 9> "$WORK_DIR/.build.lock"
flock -n 9 || die "another build is already running (lock: $WORK_DIR/.build.lock)"

"$ROOT_DIR/scripts/check-consistency.sh" || die "pinned versions disagree, see above"
# mkarchiso skips steps whose stamp files exist in its work directory, so a
# leftover work dir would silently produce an ISO with the OLD root filesystem.
# Always start it fresh (downloaded packages stay in the pacman cache).
sudo rm -rf "$archiso_work"
if [[ "${1:-}" == "--clean" ]]; then
    sudo rm -rf "$WORK_DIR/chroot" "$WORK_DIR/stamps" "$WORK_DIR/pkgbuilds" "$WORK_DIR/aur"
    rm -f "$LOCAL_REPO_DIR"/*.pkg.tar.* "$LOCAL_REPO_DIR/$LOCAL_REPO_NAME".{db,files}*
fi

msg "1/5 Theme"
"$ROOT_DIR/scripts/make-theme.sh"

msg "2/5 Packages"
if [[ -n "${CELESTIA_RESTORE:-}" ]]; then
    # Take the packages the update channel already publishes (exactly what installed
    # systems will get); only what is missing or changed is built.
    LOCAL_REPO_NAME="celestia-$(detect_channel)" "$ROOT_DIR/scripts/repo-release.sh" restore
    export LOCAL_REPO_NAME="celestia-$(detect_channel)"
fi
"$ROOT_DIR/scripts/build-packages.sh"

msg "3/5 Offline driver repo"
"$ROOT_DIR/scripts/fetch-offline-repo.sh"

msg "4/5 Assembling the archiso profile"
sudo rm -rf "$profile_dir"
cp -r "$ROOT_DIR/profile" "$profile_dir"
cp "$BUILD_PACMAN_CONF" "$profile_dir/pacman.conf"
{
    echo "# Generated by build.sh from packages/system.txt and packages/live.txt"
    cat "$RESOLVED_LIST"
} > "$profile_dir/packages.x86_64"

airootfs="$profile_dir/airootfs"
apply_march "$airootfs/etc/pacman.conf"

# Update channel of the installed system: where `pacman -Syu` finds Celestia packages.
channel="$(detect_channel)"
msg2 "update channel of this ISO: $channel"
install -d "$airootfs/etc/celestia"
echo "$channel" > "$airootfs/etc/celestia/channel"
echo "$CELESTIA_REPO" > "$airootfs/etc/celestia/repo"
render_channel_conf "$channel" > "$airootfs/etc/pacman.d/celestia.conf"
# Not /etc/calamares: the Calamares package owns files there. celestia-installer
# copies this over /etc/calamares when the live system starts.
install -d "$airootfs/usr/share/celestia-installer"
cp -r "$ROOT_DIR/calamares" "$airootfs/usr/share/celestia-installer/calamares"
sed -i "s|^region:.*|region:                     \"$DEFAULT_TIMEZONE_REGION\"|;
        s|^zone:.*|zone:                       \"$DEFAULT_TIMEZONE_ZONE\"|" \
    "$airootfs/usr/share/celestia-installer/calamares/modules/locale.conf"
ln -sf "/usr/share/zoneinfo/$DEFAULT_TIMEZONE_REGION/$DEFAULT_TIMEZONE_ZONE" "$airootfs/etc/localtime"
install -d "$airootfs/opt"
cp -r "$OFFLINE_REPO_DIR" "$airootfs/opt/celestia-offline"

msg "5/5 Building the ISO (mkarchiso)"
mkdir -p "$out_dir"
sudo mkarchiso -v -w "$archiso_work" -o "$out_dir" "$profile_dir"
sudo chown "$(id -u):$(id -g)" "$out_dir"/*.iso

iso="$(ls -t "$out_dir"/*.iso | head -n1)"
(cd "$out_dir" && sha256sum "$(basename "$iso")" > "$(basename "$iso").sha256")
# AUR commits used for this ISO; copy to packages/aur.lock to rebuild exactly these.
cp "$WORK_DIR/aur.lock" "$out_dir/$(basename "$iso" .iso).aur.lock" 2>/dev/null || true
msg "Done: $iso ($(du -h "$iso" | cut -f1))"
